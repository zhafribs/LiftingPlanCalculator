/**
 * The gate, in every state it can be in.
 *
 * Each branch says what to **do**, not merely what happened.  "You are not on the
 * approved list" is an outcome an operator can act on — they ask whoever gave them
 * the app — while "authentication failed" sends them to a person who cannot help.
 *
 * [Admission.Allowed] is deliberately not handled: the caller shows the app instead,
 * and a branch for it would be a screen that should never render.
 */
@Composable
fun SignInScreen(
    viewModel: AuthViewModel,
    admission: Admission,
    modifier: Modifier = Modifier,
) {
    var email by rememberSaveable { mutableStateOf("") }
    var password by rememberSaveable { mutableStateOf("") }
    var creating by rememberSaveable { mutableStateOf(false) }

    val context = LocalContext.current
    // `LocalResources`, not `context.getString` -- resource reads through the
    // context are not configuration-aware and can serve a stale value after a
    // locale or density change.  Lint fails the release build over it, and it is
    // right to.
    val resources = LocalResources.current
    val scope = rememberCoroutineScope()
    val serverClientId = remember(resources) {
        // Generated by the Google services plugin from the project's **web** client.
        // Read rather than pasted in, so the project's identity has one home.
        runCatching { resources.getString(R.string.default_web_client_id) }.getOrNull()
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 24.dp, vertical = 28.dp),
        verticalArrangement = Arrangement.spacedBy(20.dp),
    ) {
        Header()

        when (admission) {
            Admission.SignIn -> {
                SectionCard(title = if (creating) "Create an account" else "Sign in") {
                    // Google first: it is one tap, and its address arrives already
                    // proved, so it is the shorter road from here to a plan.
                    if (serverClientId != null) {
                        GoogleButton(
                            enabled = !viewModel.busy,
                            onClick = {
                                scope.launch {
                                    try {
                                        googleIdToken(context, serverClientId)?.let {
                                            viewModel.signInWithGoogle(it)
                                        }
                                    } catch (failure: AuthFailure) {
                                        viewModel.reportFailure(
                                            failure.message ?: "Google sign-in did not work."
                                        )
                                    }
                                }
                            },
                        )
                        OrDivider()
                    }

                    LabeledTextField(
                        label = "Email",
                        value = email,
                        onValueChange = { email = it },
                        hint = "you@example.com",
                    )
                    PasswordField(
                        label = "Password",
                        value = password,
                        onValueChange = { password = it },
                    )
                    Button(
                        onClick = {
                            if (creating) {
                                viewModel.signUp(email, password)
                            } else {
                                viewModel.signIn(email, password)
                            }
                        },
                        enabled = !viewModel.busy,
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(
                            when {
                                viewModel.busy -> "Please wait\u2026"
                                creating -> "Create account"
                                else -> "Sign in"
                            }
                        )
                    }
                    // Offered on the sign-in form only, not while creating an
                    // account: someone who has no account has nothing to reset.
                    if (!creating) {
                        TextButton(
                            onClick = { viewModel.sendPasswordReset(email) },
                            enabled = !viewModel.busy,
                            modifier = Modifier.fillMaxWidth(),
                        ) {
                            Text("Forgot password?")
                        }
                    }
                    TextButton(
                        onClick = {
                            creating = !creating
                            viewModel.dismissMessage()
                        },
                        enabled = !viewModel.busy,
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(
                            if (creating) {
                                "I already have an account"
                            } else {
                                "I do not have an account yet"
                            }
                        )
                    }
                    if (creating) {
                        Text(
                            text = "You will be asked to confirm your email address " +
                                "before the app will open. Access is granted by the " +
                                "person who gave you this app, not by creating an " +
                                "account.",
                            color = TextMuted,
                            style = MaterialTheme.typography.bodySmall,
                        )
                    }
                }
            }

            is Admission.Verify -> {
                SectionCard(title = "Confirm your email") {
                    Text(
                        text = "A confirmation link has been sent to " +
                            "${admission.email}. Open it, then come back and press " +
                            "the button below.",
                        color = TextPrimary,
                        style = MaterialTheme.typography.bodyMedium,
                    )
                    Button(
                        onClick = viewModel::refresh,
                        enabled = !viewModel.busy,
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(if (viewModel.busy) "Checking\u2026" else "I have verified")
                    }
                    TextButton(
                        onClick = viewModel::resendVerification,
                        enabled = !viewModel.busy,
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text("Send the email again")
                    }
                    // Why this step exists, in the operator's own terms.
                    Text(
                        text = "This step is what makes the approved list mean " +
                            "anything: without it, someone could sign up with an " +
                            "address that is on the list without being able to " +
                            "receive mail at it.",
                        color = TextMuted,
                        style = MaterialTheme.typography.bodySmall,
                    )
                }
                SignOutRow(viewModel)
            }

            is Admission.NotOnTheList -> {
                SectionCard(title = "Not an approved address") {
                    Text(
                        text = "${admission.email} is not on the approved list, so " +
                            "this app will not open for it.",
                        color = StateOver,
                        style = MaterialTheme.typography.bodyMedium,
                        fontWeight = FontWeight.Bold,
                    )
                    Text(
                        text = "If you should have access, ask ${Contact.NAME} to add " +
                            "this exact address. It is the address you signed in with, " +
                            "and it has to match.",
                        color = TextMuted,
                        style = MaterialTheme.typography.bodySmall,
                    )

                    // **The request, made for them.**  Pressing this opens their own
                    // mail app with the developer's address, their address to
                    // approve, and a subject line already written -- so the message
                    // that arrives is one somebody can act on, and replying to it
                    // goes straight back to the person asking.
                    Text(
                        text = Contact.EMAIL,
                        color = TextPrimary,
                        style = MaterialTheme.typography.bodyMedium,
                        fontWeight = FontWeight.Bold,
                    )
                    if (Contact.PHONE != null) {
                        Text(
                            text = Contact.PHONE,
                            color = TextPrimary,
                            style = MaterialTheme.typography.bodyMedium,
                            fontWeight = FontWeight.Bold,
                        )
                    }
                    Button(
                        onClick = {
                            if (!Contact.requestAccess(context, admission.email)) {
                                viewModel.reportFailure(
                                    "No mail app was found on this device. Write to " +
                                        "${Contact.EMAIL} instead, quoting " +
                                        "${admission.email}."
                                )
                            }
                        },
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text("Request access")
                    }
                }
                SignOutRow(viewModel)
            }

            is Admission.CouldNotCheck -> {
                SectionCard(title = "Could not check the approved list") {
                    Text(
                        text = "You are signed in as ${admission.email}, but the " +
                            "approved list could not be reached.",
                        color = StateCaution,
                        style = MaterialTheme.typography.bodyMedium,
                        fontWeight = FontWeight.Bold,
                    )
                    Text(
                        text = "If you have been approved before, this is usually " +
                            "just a signal problem: connect once and press Try " +
                            "again, and the app will remember the answer afterwards.",
                        color = TextMuted,
                        style = MaterialTheme.typography.bodySmall,
                    )
                    Button(
                        onClick = viewModel::refresh,
                        enabled = !viewModel.busy,
                        modifier = Modifier.fillMaxWidth(),
                    ) {
                        Text(if (viewModel.busy) "Checking\u2026" else "Try again")
                    }
                }
                SignOutRow(viewModel)
            }

            // Unreachable: the caller renders the app instead of this screen.
            is Admission.Allowed -> Unit
        }

        if (viewModel.message != null) {
            Text(
                text = viewModel.message!!,
                color = StateOver,
                style = MaterialTheme.typography.bodySmall,
            )
        }

        Box(Modifier.fillMaxWidth())
    }
}

/** The app's face: its own icon, its name, and who may use it. */
@Composable
private fun Header() {
    Column(
        modifier = Modifier.fillMaxWidth(),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        Image(
            painter = painterResource(R.drawable.crane_logo),
            // Decorative: the name is right underneath it, and a screen reader
            // announcing both would say the same thing twice.
            contentDescription = null,
            contentScale = ContentScale.Fit,
            modifier = Modifier.size(120.dp),
        )
        Text(
            text = "Lifting Plan Calculator",
            color = TextPrimary,
            style = MaterialTheme.typography.headlineSmall,
            fontWeight = FontWeight.Bold,
            textAlign = TextAlign.Center,
        )
        Text(
            text = "For approved users only",
            color = TextMuted,
            style = MaterialTheme.typography.bodyMedium,
            textAlign = TextAlign.Center,
        )
    }
}

@Composable
private fun GoogleButton(enabled: Boolean, onClick: () -> Unit) {
    OutlinedButton(
        onClick = onClick,
        enabled = enabled,
        modifier = Modifier.fillMaxWidth(),
    ) {
        Text("Continue with Google")
    }
}

/**
 * "or" with a rule either side.
 *
 * A divider with the word sitting on it, rather than a plain line: two sign-in
 * methods offered side by side, one of which involves leaving the app, need saying
 * that they are alternatives.
 */
@Composable
private fun OrDivider() {
    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(10.dp),
    ) {
        HorizontalDivider(modifier = Modifier.weight(1f))
        Text(
            text = "or",
            color = TextMuted,
            style = MaterialTheme.typography.labelMedium,
        )
        HorizontalDivider(modifier = Modifier.weight(1f))
    }
}

@Composable
private fun SignOutRow(viewModel: AuthViewModel) {
    TextButton(
        onClick = viewModel::signOut,
        colors = ButtonDefaults.textButtonColors(contentColor = Danger),
        modifier = Modifier.fillMaxWidth(),
    ) {
        Text("Sign out")
    }
}
